export type Key = keyof typeof dict.tg;

const Ctx = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key) => string;
}>({ lang: "tg", setLang: () => {}, t: (k) => dict.tg[k] });

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("tg");

  useEffect(() => {
    const saved = localStorage.getItem("nurov-lang") as Lang | null;
    if (saved && dict[saved]) setLangState(saved);
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("nurov-lang", l);
    document.documentElement.lang = l === "tg" ? "tg" : l;
  };

  const t = useMemo(() => (k: Key) => dict[lang][k], [lang]);
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}
